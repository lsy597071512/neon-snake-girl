const EVENING = [18, 19, 20, 21];
const NIGHT = [22, 23, 0, 1, 2, 3, 4];
const MORNING = [5, 6, 7, 8, 9];

const SOCIAL_JOIN: CampEventReactionKind[] = ['help', 'spectate', 'investigate', 'recruit'];

function ev(partial: CampEventDef): CampEventDef {
  const allowsCoScreen =
    partial.allowsCoScreen ??
    (partial.tags.includes('social') || partial.tags.includes('chat'));
  return {
    ...partial,
    allowsCoScreen,
    joinReactions: partial.joinReactions ?? SOCIAL_JOIN,
    maxJoiners:
      partial.maxJoiners ?? (allowsCoScreen ? MAX_CO_SCREEN_JOINERS : undefined),
  };
}

