export function getDisciplinePoseCount(characterId: string): number {
  return getCharacterSkin(characterId, DISCIPLINE_SKIN_ID)?.portraitLiveSecondaries?.length ?? 0;
}

export function getDisciplinePoseNote(characterId: string, poseIndex: number | null): string {
  if (poseIndex == null || poseIndex <= 0) return IDLE_NOTE;
  const custom = DISCIPLINE_POSE_NOTES[characterId]?.[poseIndex];
  if (custom) return custom;
  return GENERIC_POSE[poseIndex] ?? `姿势${poseIndex}：束缚点加重，姿态被机械触手重新固定。`;
}

/** 玩家侧发送的姿势切换文本（触手调教态） */
export function buildDisciplinePosePlayerMessage(
  characterId: string,
  poseIndex: number,
): string {
  const note = getDisciplinePoseNote(characterId, poseIndex);
  return `（你将拘束姿态切换为姿势${poseIndex}——进入触手调教：${note}）`;
}

/** 玩家侧：回到未调教 idle */
export function buildDisciplineIdlePlayerMessage(characterId: string): string {
  const note = getDisciplinePoseNote(characterId, null);
  return `（你解除触手加压姿势，让她回到未调教待机：${note}）`;
}
