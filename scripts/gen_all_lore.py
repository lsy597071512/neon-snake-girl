def cjk(s: str) -> int:
    return len(re.findall(r"[\u4e00-\u9fff]", s))


def join_parts(*parts: str) -> str:
    return "\n\n".join(p.strip() for p in parts if p and p.strip()) + "\n"


def pad(name: str, text: str, extras: list[str], min_n: int = 2000) -> str:
    t = text.strip()
    i = 0
    while cjk(t) < min_n:
        t += "\n\n" + extras[i % len(extras)].format(name=name)
        i += 1
        if i > 30:
            break
    return t + "\n"


