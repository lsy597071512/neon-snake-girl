function countHan(str) {
  return (str.match(/[\u4e00-\u9fff]/g) || []).length;
}

function padStory(story, minHan, padParagraph) {
  let s = story;
  while (countHan(s) < minHan) {
    s += '\n\n' + padParagraph;
  }
  return s;
}

