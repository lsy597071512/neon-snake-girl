/**
 * 从 shinei01_*lou_luxian 提取白色路线 → 百分比航点网格
 * 输出：src/data/campRouteGraph.generated.ts
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const indoor = path.join(root, 'tex', 'Indoor');

const SOURCES = [
  { floor: 1, file: 'shinei01_1lou_luxian.jpg' },
  { floor: 2, file: 'shinei01_2lou_luxian.png' },
];

/** 下采样网格：每格覆盖原图像素 */
const CELL = 8;
/** 白色判定：RGB 均高且接近 */
function isWhite(r, g, b, a) {
  if (a < 200) return false;
  const min = Math.min(r, g, b);
  const max = Math.max(r, g, b);
  return min >= 200 && max - min <= 45;
}

async function extractFloor(floor, file) {
  const abs = path.join(indoor, file);
  if (!fs.existsSync(abs)) throw new Error(`missing ${abs}`);
  const { data, info } = await sharp(abs).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info;
  const cols = Math.ceil(width / CELL);
  const rows = Math.ceil(height / CELL);
  const walk = new Uint8Array(cols * rows);

  for (let gy = 0; gy < rows; gy++) {
    for (let gx = 0; gx < cols; gx++) {
      let hits = 0;
      let samples = 0;
      const x0 = gx * CELL;
      const y0 = gy * CELL;
      for (let y = y0; y < Math.min(y0 + CELL, height); y += 2) {
        for (let x = x0; x < Math.min(x0 + CELL, width); x += 2) {
          const i = (y * width + x) * channels;
          samples++;
          if (isWhite(data[i], data[i + 1], data[i + 2], data[i + 3])) hits++;
        }
      }
      if (samples > 0 && hits / samples >= 0.08) {
        walk[gy * cols + gx] = 1;
      }
    }
  }

  // 连通邻接（4-邻）→ 节点列表（百分比坐标）
  const nodes = [];
  const indexOf = new Map();
  for (let gy = 0; gy < rows; gy++) {
    for (let gx = 0; gx < cols; gx++) {
      if (!walk[gy * cols + gx]) continue;
      const id = nodes.length;
      indexOf.set(`${gx},${gy}`, id);
      const cx = ((gx + 0.5) * CELL) / width;
      const cy = ((gy + 0.5) * CELL) / height;
      nodes.push({
        x: Math.round(cx * 1000) / 10,
        y: Math.round(cy * 1000) / 10,
      });
    }
  }

  const edges = [];
  const dirs = [
    [1, 0],
    [0, 1],
    [1, 1],
    [1, -1],
  ];
  for (let gy = 0; gy < rows; gy++) {
    for (let gx = 0; gx < cols; gx++) {
      const a = indexOf.get(`${gx},${gy}`);
      if (a == null) continue;
      for (const [dx, dy] of dirs) {
        const b = indexOf.get(`${gx + dx},${gy + dy}`);
        if (b == null) continue;
        edges.push([a, b]);
      }
    }
  }

  return { floor, width, height, cell: CELL, nodeCount: nodes.length, edgeCount: edges.length, nodes, edges };
}

const floors = {};
for (const s of SOURCES) {
  const g = await extractFloor(s.floor, s.file);
  console.log(`floor ${s.floor}: nodes=${g.nodeCount} edges=${g.edgeCount}`);
  floors[s.floor] = {
    nodes: g.nodes,
    edges: g.edges,
  };
}

const outPath = path.join(root, 'src', 'data', 'campRouteGraph.generated.ts');
const body = `/** AUTO-GENERATED by scripts/extract-camp-routes.mjs — do not edit */
export type CampRouteNode = { x: number; y: number };
export type CampRouteFloorGraph = {
  nodes: CampRouteNode[];
  edges: [number, number][];
};

export const CAMP_ROUTE_GRAPH: Record<1 | 2, CampRouteFloorGraph> = ${JSON.stringify(floors, null, 2)} as Record<1 | 2, CampRouteFloorGraph>;
`;
fs.writeFileSync(outPath, body, 'utf8');
console.log('wrote', outPath);
